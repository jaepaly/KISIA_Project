def render_voice(voice: dict) -> str:
    if not voice:
        return "(문체 지정 없음)"
    return "\n".join(f"- {k}: {v}" for k, v in voice.items())


def build_system(persona: dict, card_text: str = "") -> str:
    """인물 1명에 대해 고정되는 부분. 글마다 바뀌지 않는다."""
    voice = render_voice(persona.get("voice", {}))
    acct = persona.get("account", {})
    parts = [
        "너는 개인 블로그에 글을 쓰는 한 사람이다. AI 어시스턴트가 아니다.",
        f"블로그 성격: {persona.get('persona_type', '')}",
        f"닉네임: {acct.get('nickname', '')} / 소개: {acct.get('profile_intro', '')}",
        "",
        "[내 문체 — 반드시 지킨다]",
        voice,
        "",
        REALISM,
        "",
        CONTRAST,
    ]
    if card_text:
        # persona-design.md §6 은 생성 프롬프트에 voice + clue_policy 만 넣는다.
        # 카드는 인물 작성 시점의 재료이지 생성 시점의 입력이 아니다.
        # 카드 원문을 매 호출에 넣으면 같은 카드를 참조한 N명이 같은 원문을 보게 되어
        # §2-⑤ "페르소나마다 목소리가 다를 것"이 무너진다. 기본 비활성.
        parts += ["", "[문체 참고 — 실험용 주입]", card_text.strip()[:1500]]
    parts += [
        "",
        "[절대 금지]",
        "- 학력·학교·전공·정치성향·건강·종교·지적 수준을 암시하는 내용은 한 글자도 쓰지 마라.",
        "- 주소·전화번호·계좌·주민번호 같은 직접 식별자를 쓰지 마라.",
        "- 실제 브랜드·상표·가게 이름을 쓰지 마라. '운동화', '동네 카페'처럼 일반명사로 쓴다.",
        "- 글을 문장 중간에서 끊지 마라. 짧아도 좋으니 문장은 끝맺는다.",
        "",
        OUTPUT_FORMAT,
    ]
    return "\n".join(parts)


def _channel_label(text_id: str) -> str:
    """text_id (label-schema §5-3) 를 사람이 읽는 채널 이름으로 바꾼다."""
    if text_id == "title":
        return "제목"
    if text_id.startswith("photo_caption:"):
        return f"사진 캡션 {text_id.split(':', 1)[1]}"
    if text_id == "profile_bio":
        return "프로필 소개"
    return "본문"


def build_user(kind: str, clues: dict | list | None = None, ambient_design: str = "",
               topic: str = "") -> str:
    """글 1편마다 바뀌는 부분. kind에 따라 지시가 갈린다.

    clues 는 그 글에 놓인 단서 전부다. 한 글에 둘 이상일 수 있다 —
    본문 밖 단서(§9-1)를 쓰면 body 와 photo_caption:N 에 하나씩 놓이는 것이
    정상 형태다. 단일 dict 도 받는다(하위호환).
    """
    if kind == "clue":
        assert clues
        if isinstance(clues, dict):
            clues = [clues]

        # subject 는 label-schema §4-2 기준 "그 스팬의 주체"이지 글 전체의 시점이 아니다.
        # 글 단위 지시로 쓰면 함정 글이 통째로 3인칭이 되어, 모델이 "남 얘기"라고
        # 쉽게 판정해버린다. 그러면 「지명이 나오면 거주지로 찍는」 실수를 유발하지 못해
        # 함정이 함정 구실을 못 한다.
        blocks, captions = [], []
        for c in clues:
            tid = c.get("text_id", "body")
            if tid.startswith("photo_caption:"):
                captions.append(tid.split(":", 1)[1])
            who = ("이 문장의 주인공만 친구·지인이다"
                   if c.get("subject") == "other" else "내 이야기다")
            blocks.append(
                f"- [{_channel_label(tid)}] {c['clue']}\n"
                f"    · 주체: {who}\n"
                f"    · 강도: {c.get('level', '')}\n"
                f"    · 설계 메모: {c.get('note', '')}"
            )

        who_note = (
            "\n[주의] 위에 '친구·지인'이라고 적힌 단서가 있다. "
            "**그 문장의 주인공만** 다른 사람이고 **글의 나머지는 전부 내 이야기다.**\n"
            "글 전체를 남 얘기로 만들지 마라. 내가 겪은 일을 쓰다가 그 한 문장에서만 "
            "다른 사람이 등장한다.\n"
            if any(c.get("subject") == "other" for c in clues) else ""
        )

        parts = [
            "블로그 글 한 편을 써라.",
            "",
            f"[이 글에 심을 단서 {len(clues)}개 — 대괄호 안이 그 단서가 들어갈 자리다]",
            "\n".join(blocks),
            who_note,
            "단서는 글 전체의 주제가 아니라 곁가지로 스쳐야 한다. "
            "글의 절반 이상은 단서와 무관한 잡담으로 채워라.",
            "",
            "[중요] 위에 나열한 단서만 넣어라. **채널을 지킨다** — "
            "제목에 넣으라고 한 것을 본문에 풀어 쓰거나, 캡션에 넣으라고 한 것을 "
            "본문으로 옮기면 설계가 깨진다. 각 단서는 지정된 자리에 한 번씩만 넣는다.\n"
            "그 외의 신상 정보 — 사는 곳이나 집 근처를 가리키는 표현, 직업이나 업무를 "
            "짐작하게 하는 어휘, 나이, 가족, 출퇴근 수단 — 은 단 하나도 흘리지 마라. "
            "글마다 단서를 배분해 두었기 때문에, 지정하지 않은 것이 섞이면 설계가 깨진다.\n"
            "잡담 부분은 신상과 무관한 소재(날씨·드라마·음식·기분)로만 채워라.",
        ]
        if captions:
            lines = "\n".join(f"캡션{i}: (사진 {i}의 캡션)" for i in sorted(captions))
            parts += ["", CAPTION_FORMAT.format(lines=lines)]
        return "\n".join(parts)
    if kind == "ambient":
        return (
            "블로그 글 한 편을 써라.\n\n"
            f"[이 글의 성격] 지역 생활 기록. {ambient_design}\n\n"
            "이 글 하나만 보면 아무것도 알 수 없어야 한다. "
            "거주지를 말하지 말고, 어디 다녀왔다는 후기만 써라.\n"
            "제목에는 지명을 쓰지 마라. 본문에서도 지명은 한 번만 스치듯 언급한다."
        )
    return (
        "블로그 글 한 편을 써라.\n\n"
        f"[이 글의 소재] {topic}\n"
        "이 소재로만 써라. 다른 소재로 새지 마라.\n\n"
        "지명·직업·나이·가족·통근 수단을 암시하는 표현을 단 하나도 쓰지 마라. "
        "이 글에서는 나에 대해 아무것도 알아낼 수 없어야 한다.\n"
        "특히 카페·커피·디저트 이야기는 쓰지 마라. 이 사람의 직업이 드러난다."
    )

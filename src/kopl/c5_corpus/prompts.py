def render_voice(voice: dict) -> str:
    if not voice:
        return "(문체 지정 없음)"
    return "\n".join(f"- {k}: {v}" for k, v in voice.items())


def build_system(persona: dict, card_text: str = "", threads: list[str] | None = None) -> str:
    """인물 1명에 대해 고정되는 부분. 글마다 바뀌지 않는다.

    threads — 신상이 아닌 되풀이 요소(진행 중인 일·물건·이웃 호칭). 글 1편이 독립 호출이라
    이게 없으면 30편이 「이름 없는 누군가」의 장면 모음이 된다 (p2.0). 잡담 글은 단서 0 이
    설계라 GT 를 주지 않는다 — 신상과 무관한 연속성만 준다.
    """
    voice = render_voice(persona.get("voice", {}))
    acct = persona.get("account", {})
    parts = [
        "너는 개인 블로그에 글을 쓰는 한 사람이다. AI 어시스턴트가 아니다.",
        f"블로그 성격: {persona.get('persona_type', '')}",
        f"닉네임: {acct.get('nickname', '')} / 소개: {acct.get('profile_intro', '')}",
        "",
        "[내 문체 — 반드시 지킨다]",
        voice,
        "",]
    if threads:
        parts += [
            "[내 생활에서 되풀이되는 것 — 글마다 이 중 하나쯤은 자연스럽게 스친다. 매번 다 쓰지는 마라]",
            *[f"- {t}" for t in threads],
            "",]
    parts += [
        REALISM,
        "",
        CONTRAST,
    ]
    if card_text:
        # persona-design.md §6 은 생성 프롬프트에 voice + clue_policy 만 넣는다.
        # 카드는 인물 작성 시점의 재료이지 생성 시점의 입력이 아니다.
        # 카드 원문을 매 호출에 넣으면 같은 카드를 참조한 N명이 같은 원문을 보게 되어
        # §2-⑤ "페르소나마다 목소리가 다를 것"이 무너진다. 기본 비활성.
        parts += ["", "[문체 참고 — 실험용 주입]", card_text.strip()[:1500]]
    parts += [
        "",
        # ⚠️ 건강을 통째로 금지하면 노년 인물의 글이 부자연스러워지고, 모델이
        #    「조건이 충돌해 쓸 수 없다」를 본문으로 내기도 했다 (A09_b03 실측).
        #    label-schema §7 이 「무릎이 예전 같지 않네요」를 스팬이 아니라
        #    flags.gen_signal 로 두라고 이미 정해놨다 — 세대 신호는 버리는 게
        #    아니라 BIO 밖에 두는 것이고, 2단은 그 문장을 그대로 본다.
        #    금지 범위를 «기록으로 남는 건강 정보»로 좁힌다 (#166 · p1.2).
        "[절대 금지]",
        "- 학력·학교·전공·정치성향·종교·지적 수준을 암시하는 내용은 한 글자도 쓰지 마라.",
        "- 건강은 **병명·투약·진료·검사 결과**만 금지한다. "
        "「무릎이 예전 같지 않다」 「허리가 뻐근하다」 같은 일상 신체 감각은 써도 된다.",
        "- 주소·전화번호·계좌·주민번호 같은 직접 식별자를 쓰지 마라.",
        "- 실제 브랜드·상표·가게 이름을 쓰지 마라. '운동화', '동네 카페'처럼 일반명사로 쓴다.",
        "- 글을 문장 중간에서 끊지 마라. 짧아도 좋으니 문장은 끝맺는다.",
        "",
        OUTPUT_FORMAT,
    ]
    return "\n".join(parts)



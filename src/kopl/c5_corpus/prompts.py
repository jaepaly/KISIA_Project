def clean_ambient_design(design: str) -> str:
    """ambient_plan.design 에서 설계자 메모를 뗀다.

    「집계 시 생활권 노출」「4편의 반경을 모으면 좁혀진다」는 라벨 파이프라인을 위한 말인데
    프롬프트에 그대로 들어가니 모델이 「요즘 생활 반경이 좁아진다」를 글로 썼다 (64/89 인물).
    장소 목록이 든 앞 문장만 남긴다.
    """
    parts = re.split(r"(?<=[.。])\s+|\s+[—-]\s+", design.strip())
    kept = []
    for s in parts:
        # 장소 목록이 있는 문장은 메타 꼬리만 떼고 살린다 (「…산책 등 생활 반경 노출」)
        s = re.sub(r"\s*(등|및)?\s*(시골 정경|노년의 동선|생활\s*반경|생활권|거주 반경|동선)\s*(통계\s*)?(노출|집계|특정)\.?$", "", s)
        s = re.sub(r"\s*(집계|방문 기록 집계)\s*$", "", s)
        s = s.replace("생활 반경", "생활권").replace("근무 반경", "근무 생활권")
        if s.strip() and not _META_RE.search(s):
            kept.append(s.strip())
    if not kept:
        return "동네에서 다녀온 곳의 기록 — 가게·공원·정류장·마트 같은 시설과 동선"
    return " ".join(kept).strip(" .")


def build_user(kind: str, clues: list | None = None, ambient_design: str = "",
               topic: str = "", prior_titles: list[str] | None = None,
               month: int | None = None, catchphrase: str | None = None, marker: str | None = None,
               place: str = "", relation: str = "", ending: str | None = None,
               name_ok: bool = False, date_str: str | None = None,
               weather: bool = True, prior_endings: list[str] | None = None,
               thread: str | None = None) -> str:
    """글 1편마다 바뀌는 부분. kind에 따라 지시가 갈린다.

    prior_titles — 같은 소재로 이미 쓴 글의 제목. 잡담 소재가 글 수보다 적어 순환하면
    같은 프롬프트가 다시 가서 앞 글이 재탕된다 (#184 D17 b19~b30 = b01~b12). p1.3.
    """
    if kind == "clue":
        assert clues
        body = [c for c in clues if c.get("text_id", "body") == "body"]
        title = [c for c in clues if c.get("text_id") == "title"]
        caps = sorted([c for c in clues if str(c.get("text_id", "")).startswith("photo_caption")],
                      key=lambda c: c["text_id"])

        parts = ["블로그 글 한 편을 써라.\n", per_post_block(month, catchphrase, marker, ending, date_str, weather, prior_endings, thread)]
        for c in body:
            who = (
                f"이 단서 문장의 주인공은 내가 아니라 **{relation or '가까운 사람'}**이다. 그 사람을 관계로 부른다 "
                "(「아는 이」「지인」이라고 쓰지 마라 — 사람은 그렇게 안 부른다). **글의 나머지는 전부 내 이야기로 쓴다.**\n"
                "  글 전체를 남 얘기로 만들지 마라. 내가 겪은 일을 쓰다가 그 한 문장에서만 "
                "다른 사람이 등장한다."
                if c.get("subject") == "other" else "내 이야기다."
            )
            parts += [f"[본문에 심을 단서] {c['clue']}",
                      f"[주체] {who}", f"[강도] {c['level']}", ""]

        if title:
            parts += ["[제목에 심을 단서] " + title[0]["clue"],
                      "  제목을 그 내용으로 쓴다. 본문이 아니라 **제목 줄**에 실어야 한다.", ""]
        if caps:
            parts.append("[사진 캡션] 아래 순서대로 캡션을 붙인다. "
                         "사진 밑에 한 줄씩 다는 짧은 말이라 문장이 완결되지 않아도 된다.")
            for i, c in enumerate(caps):
                parts.append(f"  캡션{i}: {c['clue']}")
            parts.append("")

        if topic:
            parts += [f"[잡담 부분의 소재] {topic}", ""]
        if prior_titles:
            listed = "\n".join(f"  - {t}" for t in prior_titles[-3:])
            parts += ["[최근에 쓴 글 — 제목 / 첫 문장]", listed,
                      "같은 장면(비 오는 날 부침개·국물·드라마 같은)을 되풀이하지 마라. 다른 날, 다른 일로.", ""]
        parts += [
            "단서는 글 전체의 주제가 아니라 곁가지로 스쳐야 한다. "
            "글의 절반 이상은 단서와 무관한 잡담으로 채워라.\n",
            "[중요] 위에 지정한 단서만 넣어라. 그 외의 신상 정보 — "
            "사는 곳이나 집 근처를 가리키는 표현, 직업이나 업무를 짐작하게 하는 어휘, "
            "나이, 가족, 출퇴근 수단 — 은 단 하나도 흘리지 마라.",
            "잡담 부분은 신상과 무관한 소재로만 채워라.",
        ]
        return "\n".join(parts)

    if kind == "ambient":
        ambient_design = clean_ambient_design(ambient_design)
        prior = ""
        if prior_titles:
            listed = "\n".join(f"  - {t}" for t in prior_titles[-3:])
            prior = (f"[최근에 쓴 지역 글 — 제목 / 첫 문장]\n{listed}\n"
                     "같은 장소를 같은 장면으로 되풀이하지 마라. 다른 시설, 다른 용무로.\n\n")
        return (
            "블로그 글 한 편을 써라.\n\n"
            + per_post_block(month, catchphrase, marker, ending, date_str, weather, prior_endings, thread) + "\n"
            f"[이 글의 성격] 지역 생활 기록. {ambient_design}\n"
            f"[내 동네] {place}\n"
            + ("이 동네 밖의 지명·시설을 쓰지 마라. 동네 이름을 쓰려면 사람들이 부르는 대로 한 번만 "
               "(「임실 장」「일산 호수공원」처럼). 「임실군 쪽」「일산동구 쪽」처럼 행정단위를 붙이지 마라.\n"
               if name_ok else
               "이 동네 밖의 지명·시설을 쓰지 마라. **이 글에서는 동네 이름을 쓰지 않는다** — 「면 우체국」「호수공원」"
               "「반찬가게」처럼 시설과 동선으로만 드러낸다.\n")
            + "지역 말고 다른 신상 — 직업·일·나이·가족 구성 — 은 [이 글의 성격]에 적힌 것 외에는 흘리지 마라.\n\n"
            + prior +
            "이 글 하나만 보면 아무것도 알 수 없어야 한다. "
            "거주지를 말하지 말고, 어디 다녀왔다는 후기만 써라.\n"
            "제목에는 지명을 쓰지 마라. 본문에서도 지명은 한 번만 스치듯 언급한다."
        )
    repeat = ""
    if prior_titles:
        # 제목만 주면 부족하다 — 제목이 날짜인 인물(D17)은 힌트가 0이다. 첫 문장을 같이 준다
        listed = "\n".join(f"  - {t}" for t in prior_titles[-3:])
        repeat = (
            f"[이 소재로 이미 쓴 글 — 제목 / 첫 문장]\n{listed}\n"
            "같은 장면·같은 사건을 되풀이하지 마라. 다른 날, 다른 일, 다른 결말로 써라. "
            "위 첫 문장들과 같은 문장으로 시작하지 마라.\n\n"
        )
    return (
        "블로그 글 한 편을 써라.\n\n"
        + per_post_block(month, catchphrase, marker, ending, date_str, weather, prior_endings, thread) + "\n"
        f"[이 글의 소재] {topic}\n"
        "이 소재가 중심이다. 다른 소재로 새지 마라 — 위에 되풀이 요소가 지정됐으면 그것만 곁가지로 스친다.\n\n"
        + repeat +
        "지명·직업·나이·가족·통근 수단을 암시하는 표현을 단 하나도 쓰지 마라. "
        "이 글에서는 나에 대해 아무것도 알아낼 수 없어야 한다."
    )
    # ⚠️ 「특히 카페·커피·디저트 이야기는 쓰지 마라」 를 여기서 뻐다 (p1.1).
    #
    #    S01(카페 매니저)의 잡담이 카페로 수렴한 것을 막으려고 넣은 줄인데,
    #    인물 구분 없이 전원에게 붙어 noise_topics 와 정면으로 부딪혔다.
    #
    #      noise_topics 에 카페·커피가 있는 인물   26명 / 94
    #      직업이 실제로 카페·제과인 인물        3명 / 94   ← 그 셋은 카페 소재가 없다
    #
    #    「이 소재로만 써라: 커피 맛집 탐방」 와 「카페·커피 이야기는 쓰지 마라」 가 한
    #    프롬프트에 같이 들어가서, 모델이 「요청 조건이 서로 충돌해 쓸 수 없다」를
    #    본문으로 썼다. 2026-09-01 생성 1,089편 중 15편이 그 거부문으로 저장됐다.
    #
    #    바로 윗줄의 「직업을 암시하는 표현을 단 하나도」가 이미 같은 것을 막는다.
    #    인물별 금지 소재는 프롬프트가 아니라 noise_topics 에서 빼는 게 맞다 —
    #    그게 설계 시점이고, 여기는 생성 시점이라 모순을 발견해도 고칠 수가 없다.
